            [void]$state.Repos.Add($row)
            $all.Add($row)
        }
    } finally {
        $state.SuppressSelection = $false
    }

    $state.AllRepos = $all.ToArray()
    $state.ReleaseCache = @{}
    $ui.dgRepos.SelectedItem = $null
    Update-GhlRepoView
}

