        } elseif ($state.SelectedRelease) {
            $ui.txtBatchHint.Text = 'Version {0} for all selected repositories' -f $state.SelectedRelease.Tag
        } else {
            $ui.txtBatchHint.Text = 'Latest stable version for all selected repositories'
        }
    }

